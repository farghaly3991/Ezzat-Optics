/**
 * Test: Desired Product Conversion to Service/Maintenance & Phone-as-Login Auto Account
 */

const mongoose = require("mongoose");
const bcrypt = require("bcryptjs");
const path = require("path");
require("dotenv").config({ path: path.join(__dirname, "..", ".env") });
const envJson = require("../env.json");
const { getMongooseConnection, ensureTenantConnection } = require("../core/database");
const getDesiredProductModel = require("../modules/product-requests/desiredProductModel");
const getStoreOrderModel = require("../modules/orders/orderModel");
const getStoreReturnModel = require("../modules/returns/returnModel");
const getUsersModel = require("../modules/auth/userModel");
const getStoreNotificationModel = require("../modules/product-requests/notificationModel");
const { convertDesiredProductToService } = require("../modules/product-requests/productRequestsController");

async function runTest() {
  const subdomain = "localhost";
  console.log("🚀 Starting Desired Product Conversion & Auto-Account Integration Test...");

  const DB_URL = envJson[subdomain]?.database || envJson.localhost?.database;
  await ensureTenantConnection(subdomain, DB_URL);
  const conn = getMongooseConnection(subdomain);
  const DesiredProduct = await getDesiredProductModel(subdomain);
  const Users = getUsersModel(subdomain);
  const Orders = getStoreOrderModel(subdomain);
  const Returns = getStoreReturnModel(subdomain);
  const Notifications = await getStoreNotificationModel(subdomain);

  // Clean previous demo test data
  const testPhone = "01099887766";
  await Users.deleteMany({ phone: testPhone });
  await DesiredProduct.deleteMany({ phone: testPhone });
  await Orders.deleteMany({ "customer.phone": testPhone });
  await Returns.deleteMany({ "customer.phone": testPhone });

  // 1. Create a dummy Desired Product request (like one generated by AI Chatbot)
  const sampleRequest = await DesiredProduct.create({
    queryText: "أنا محتاج صيانة فورية لتغيير بطارية وشاشة ايفون 13 برو",
    extractedName: "صيانة وتغيير شاشة وبطارية آيفون 13 برو",
    categoryName: "صيانة وخدمات",
    specs: { model: "iPhone 13 Pro", repair: "Screen + Battery" },
    targetPrice: { min: 1500, max: 2200 },
    customerName: "أحمد كمال التجريبي",
    phone: testPhone,
    status: "pending"
  });

  console.log("✅ Created mock customer desired request:", sampleRequest._id.toString());

  // 2. Test Controller Call: Convert to Service Order
  const mockReq = {
    subdomain,
    user: { fullname: "Admin Tester", _id: new mongoose.Types.ObjectId() },
    params: { requestId: sampleRequest._id.toString() },
    body: {
      targetType: "service",
      serviceTitle: "استبدال بطارية وشاشة أصلية iPhone 13 Pro",
      estimatedCost: 1950,
      customerName: "أحمد كمال التجريبي",
      phone: testPhone,
      address: "ميدان التحرير، القاهرة",
      notes: "تسليم فوري بعد ساعتين من الاستلام",
      sendWhatsApp: false // don't send real network WA in unit test
    }
  };

  let responseData = null;
  const mockRes = {
    status: function (code) {
      this.statusCode = code;
      return this;
    },
    json: function (payload) {
      responseData = payload;
      return this;
    }
  };

  await convertDesiredProductToService(mockReq, mockRes);

  console.log("Controller response:", responseData);
  if (!responseData?.success) {
    throw new Error("convertDesiredProductToService failed: " + JSON.stringify(responseData));
  }

  // 3. Verify Customer Account creation & Login credentials
  const createdUser = await Users.findOne({ phone: testPhone });
  if (!createdUser) {
    throw new Error("Expected user account to be auto-created with phone " + testPhone);
  }
  console.log("✅ Auto Customer Account Created:", {
    _id: createdUser._id,
    fullname: createdUser.fullname,
    email: createdUser.email,
    phone: createdUser.phone
  });

  // Verify that customer password equals their phone number
  const isMatch = await bcrypt.compare(testPhone, createdUser.password);
  if (!isMatch) {
    throw new Error("Password mismatch: Customer password does not equal phone number!");
  }
  console.log("✅ Verified: Customer can log in using their phone number as username and password!");

  // 4. Verify Technical Service Record was created in unified Maintenance & Services Hub
  const createdService = await Returns.findOne({ requestNumber: responseData.convertedCode });
  if (!createdService) {
    throw new Error("Expected service record to exist in Maintenance & Services Hub: " + responseData.convertedCode);
  }
  if (createdService.type !== "maintenance" || createdService.maintenanceSource !== "direct_service") {
    throw new Error("Service flags mismatch: expected type: 'maintenance', maintenanceSource: 'direct_service'");
  }
  if (createdService.serviceFee !== 1950) {
    throw new Error("Service fee mismatch: expected 1950, got " + createdService.serviceFee);
  }
  console.log("✅ Verified Technical Service Record in Maintenance & Services Hub:", {
    requestNumber: createdService.requestNumber,
    serviceFee: createdService.serviceFee,
    maintenanceSource: createdService.maintenanceSource,
    customer: createdService.customer.name
  });

  // 5. Verify Desired Product was updated
  const updatedDesired = await DesiredProduct.findById(sampleRequest._id);
  if (updatedDesired.status !== "converted_to_service") {
    throw new Error("DesiredProduct status mismatch: expected 'converted_to_service', got " + updatedDesired.status);
  }
  if (updatedDesired.convertedOrderCode !== responseData.convertedCode) {
    throw new Error("DesiredProduct convertedOrderCode mismatch!");
  }
  console.log("✅ Verified Desired Product Updated to 'converted_to_service' with code:", updatedDesired.convertedOrderCode);

  // 6. Test converting another request to a Maintenance Ticket
  const sampleMntRequest = await DesiredProduct.create({
    queryText: "فحص لابتوب ديل لا يعمل الباور",
    extractedName: "فحص وصيانة بوردة لابتوب Dell XPS",
    phone: testPhone,
    status: "pending"
  });

  const mockMntReq = {
    subdomain,
    user: { fullname: "Admin Tester" },
    params: { requestId: sampleMntRequest._id.toString() },
    body: {
      targetType: "maintenance",
      serviceTitle: "فحص وصيانة دائرة الباور Dell XPS",
      estimatedCost: 850,
      phone: testPhone,
      notes: "الفحص في فرع المعادي",
      sendWhatsApp: false
    }
  };

  let mntResponseData = null;
  const mockMntRes = {
    status: function (code) { return this; },
    json: function (payload) { mntResponseData = payload; return this; }
  };

  await convertDesiredProductToService(mockMntReq, mockMntRes);
  console.log("Maintenance ticket conversion response:", mntResponseData);
  if (!mntResponseData?.success || !mntResponseData?.convertedCode?.startsWith("MNT")) {
    throw new Error("Failed maintenance ticket creation");
  }

  const createdTicket = await Returns.findOne({ requestNumber: mntResponseData.convertedCode });
  if (!createdTicket || createdTicket.type !== "maintenance") {
    throw new Error("Expected maintenance ticket in Returns collection");
  }
  console.log("✅ Verified Maintenance Ticket in Database:", {
    requestNumber: createdTicket.requestNumber,
    type: createdTicket.type,
    serviceFee: createdTicket.serviceFee,
    maintenanceSource: createdTicket.maintenanceSource
  });

  console.log("\n🎉 ALL CONVERSION & AUTO-ACCOUNT INTEGRATION TESTS PASSED 100%!");
  process.exit(0);
}

runTest().catch((err) => {
  console.error("❌ TEST FAILED:", err);
  process.exit(1);
});
