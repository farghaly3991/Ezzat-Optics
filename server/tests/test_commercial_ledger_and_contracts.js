const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
const envJson = require('../env.json');
const { ensureTenantConnection } = require('../core/database');

const SUBDOMAIN = 'localhost';
const DB_URL = envJson[SUBDOMAIN]?.database || envJson.localhost?.database;

const getOrdersModel = require('../modules/orders/orderModel');
const getUsersModel = require('../modules/auth/userModel');
const getBranchModel = require('../modules/branches/branchModel');
const installmentContractEngine = require('../modules/orders/installmentContractEngine');
const installmentService = require('../modules/orders/installmentService');
const commercialLedgerService = require('../modules/finance/reports/commercialLedgerService');

async function test() {
  await ensureTenantConnection(SUBDOMAIN, DB_URL);
  const Orders = getOrdersModel(SUBDOMAIN);
  const Users = getUsersModel(SUBDOMAIN);
  const Branch = getBranchModel(SUBDOMAIN);

  const admin = await Users.findOne({ role: 5 }).lean();
  const branch = await Branch.findOne({ isMain: true }).lean();

  console.log('--- TEST 1: Commercial Ledger Calculations ---');
  const ledger = await commercialLedgerService.computeCommercialLedger(SUBDOMAIN, { branchId: null });
  console.log('Revenues:', ledger.revenues);
  console.log('Assets:', ledger.assets);
  console.log('Expenses:', ledger.expenses);
  console.log('Net Results:', ledger.netResults);
  console.log('AI Insight Summary:', ledger.aiInsight?.summary);

  console.log('\n--- TEST 2: Save and Quick-Load Snapshot ---');
  const snap = await commercialLedgerService.saveAuditSnapshot(SUBDOMAIN, admin, { branchId: null });
  console.log('Saved Snapshot Number:', snap.snapshotNumber, 'Generated by:', snap.generatedByName);

  const latest = await commercialLedgerService.getLatestAuditSnapshot(SUBDOMAIN, null);
  console.log('Quick Loaded Latest Snapshot:', latest?.snapshotNumber, 'Net Profit:', latest?.netResults?.estimatedNetProfit);

  console.log('\n--- TEST 3: Installment Contract Generator & Documents ---');
  // Find or create an installment order for testing
  let testOrder = await Orders.findOne({ 'installment.isInstallment': true }).lean();
  if (!testOrder) {
    const schedule = installmentService.buildInstallmentSchedule({
      originalAmount: 15000,
      months: 12,
      interestRate: 15,
      downPayment: 3000,
      guarantor: {
        name: 'محمود عبد الرحيم (الضامن)',
        phone: '01055443322',
        nationalId: '28912011234567',
        relationship: 'والد'
      }
    });

    testOrder = await Orders.create({
      orderId: 'INST-DOC-TEST-' + Date.now(),
      branchId: branch?._id,
      userId: admin?._id,
      customer: {
        name: 'طارق حسني إبراهيم',
        phone: '01233445566',
        address: 'مدينة نصر - القاهرة'
      },
      items: [{ name: 'لابتوب ديل كور آي 7', price: 15000, quantity: 1 }],
      payment: { method: 'installment', paid: false },
      installment: schedule,
      subtotal: 15000,
      total: schedule.plan.totalAmount,
      status: 'delivered'
    });
  }

  // Generate Contract
  const contractRes = await installmentContractEngine.generateInstallmentContract(SUBDOMAIN, testOrder.orderId);
  console.log('Contract Number:', contractRes.contractNumber);
  console.log('Generated Contract Preview (First 350 chars):');
  console.log(contractRes.contractText.slice(0, 350) + '...\n');

  // Attach Document
  const docRes = await installmentService.addInstallmentDocument(
    SUBDOMAIN,
    testOrder.orderId,
    {
      docType: 'signed_contract',
      title: 'صورة العقد الورقي بعد توقيع العميل والبصمة',
      url: '/uploads/sample-signed-contract.png',
      notes: 'تم فحص التوقيع وبصمة الإبهام بالفرع'
    },
    admin
  );
  console.log('Document Attached:', docRes.document?.title, 'DocType:', docRes.document?.docType);
  console.log('Total Documents in Installment File:', docRes.documents?.length);

  // Clean up if it was created specifically
  if (testOrder.orderId.startsWith('INST-DOC-TEST')) {
    await Orders.deleteOne({ orderId: testOrder.orderId });
    console.log('Cleaned up test order.');
  }

  console.log('\nALL VERIFICATION TESTS PASSED SUCCESSFULLY!');
  process.exit(0);
}

test().catch(err => {
  console.error('Test Failed:', err);
  process.exit(1);
});
